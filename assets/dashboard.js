/* FDE Field Log — renders the dashboard from dashboard-data.json.
   That file is generated by projects/01-mcp-server/scripts/build_dashboard_data.py from the
   real server and a real test run, so nothing here is a number somebody typed by hand. */

const $ = (sel) => document.querySelector(sel);
const el = (tag, className, text) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
};

const state = { data: null, role: "viewer", errorKind: null };

async function load() {
  try {
    const response = await fetch("dashboard-data.json", { cache: "no-cache" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    state.data = await response.json();
    render();
  } catch (error) {
    showNotice(
      `Live data could not be loaded (${error.message}). The figures below come from ` +
        `dashboard-data.json, which is written by the test run — open this page over HTTP to see them.`
    );
  }
}

function showNotice(message) {
  const slot = $("#notice");
  slot.textContent = message;
  slot.hidden = false;
}

function render() {
  renderStatus();
  renderSummary();
  renderRoles();
  renderErrors();
  renderInjection();
  renderSuites();
}

/* ---------- header status ---------- */

function renderStatus() {
  const { tests, git, generated_at: generatedAt } = state.data;
  const green = tests.failures === 0 && tests.errors === 0 && tests.exit_code === 0;
  const chip = $("#live-status");
  chip.className = `live ${green ? "" : "bad"}`.trim();
  chip.replaceChildren(
    el("span", "beacon"),
    el("span", null, green ? `${tests.passed} tests passing` : `${tests.failures + tests.errors} failing`)
  );
  $("#stamp-commit").textContent = `${git.short} · ${git.subject}`.slice(0, 68);
  $("#stamp-generated").textContent = `generated ${generatedAt} from commit ${git.short}`;
}

/* ---------- summary tiles ---------- */

function renderSummary() {
  const { tests, tools, roles } = state.data;
  setTile("tests", tests.passed, `/ ${tests.total}`, `${tests.suites.length} suites · ${tests.duration_s}s`);
  setTile("surface", tools.length, "tools", `${Object.keys(roles).length} roles, least privilege by default`);
  setTile(
    "sideeffects",
    tools.filter((t) => !t.read_only).length,
    "can change things",
    "both gated behind a scope; Telegram also dry-run"
  );
}

function setTile(id, big, small, note) {
  const tile = document.getElementById(`tile-${id}`);
  if (!tile) return;
  tile.querySelector(".big").replaceChildren(document.createTextNode(`${big} `), el("small", null, small));
  tile.querySelector(".note").textContent = note;
}

/* ---------- role explorer ---------- */

function renderRoles() {
  const { roles, role_scopes: scopes } = state.data;
  const buttons = $("#role-toggles");
  // Least privileged first: the order should read like an escalation, not an alphabet.
  const ordered = Object.keys(roles).sort((a, b) => (scopes[a]?.length ?? 0) - (scopes[b]?.length ?? 0));
  buttons.replaceChildren(
    ...ordered.map((role) => {
      const button = el("button", "toggle", role);
      button.type = "button";
      button.setAttribute("aria-pressed", String(role === state.role));
      button.addEventListener("click", () => {
        state.role = role;
        renderRoles();
      });
      return button;
    })
  );
  paintMatrix();
}

function paintMatrix() {
  const { tools, roles, role_scopes: roleScopes } = state.data;
  const visible = new Set(roles[state.role] || []);
  const body = $("#matrix-body");

  body.replaceChildren(
    ...tools.map((tool) => {
      const allowed = visible.has(tool.name);
      const row = el("tr", allowed ? "allowed" : "denied");
      if (!tool.read_only) row.classList.add("effect");

      const name = el("th");
      name.scope = "row";
      name.appendChild(el("code", null, tool.name));
      row.appendChild(name);

      row.appendChild(el("td", "scope", tool.scope));

      const verdict = el("td", "verdict");
      const tag = el("span", "verdict-tag");
      tag.append(el("span", "dot"), el("span", null, allowed ? "listed and callable" : "not registered"));
      verdict.appendChild(tag);
      row.appendChild(verdict);

      // A class, not an inline style: the page ships a CSP that forbids style attributes.
      row.appendChild(el("td", "wrap-normal", tool.description));
      return row;
    })
  );

  const scopes = roleScopes[state.role] || [];
  const summary = $("#role-summary");
  summary.replaceChildren(
    el("span", null, "Visible tools:"),
    el("strong", null, `${visible.size} of ${tools.length}`),
    el("span", "scopes", `scopes: ${scopes.join("  ") || "none"}`)
  );
}

/* ---------- failure explorer ---------- */

function renderErrors() {
  const { errors } = state.data;
  if (!state.errorKind) state.errorKind = errors[0].kind;

  $("#error-toggles").replaceChildren(
    ...errors.map(({ kind }) => {
      const button = el("button", "toggle", kind);
      button.type = "button";
      button.setAttribute("aria-pressed", String(kind === state.errorKind));
      button.addEventListener("click", () => {
        state.errorKind = kind;
        renderErrors();
      });
      return button;
    })
  );

  const selected = errors.find((e) => e.kind === state.errorKind) || errors[0];
  $("#error-envelope").replaceChildren(...jsonNodes(selected.envelope));
  $("#error-guidance").textContent = selected.guidance;

  const retryable = selected.envelope.error.retryable;
  const badge = $("#error-retry");
  badge.className = `pill ${retryable ? "warn" : "idle"}`;
  badge.textContent = retryable
    ? selected.envelope.error.retry_after_s
      ? `retry after ${selected.envelope.error.retry_after_s}s`
      : "retryable"
    : "do not retry";
}

/* Minimal JSON pretty-printer: keys dimmed, booleans coloured, no library needed. */
function jsonNodes(value, indent = 0) {
  const pad = "  ".repeat(indent);
  if (value === null) return [el("span", "p", "null")];
  if (typeof value === "boolean") return [el("span", value ? "v-true" : "v-false", String(value))];
  if (typeof value === "number") return [document.createTextNode(String(value))];
  if (typeof value === "string") return [document.createTextNode(JSON.stringify(value))];

  const entries = Object.entries(value);
  const nodes = [document.createTextNode("{\n")];
  entries.forEach(([key, val], index) => {
    nodes.push(document.createTextNode(`${pad}  `));
    nodes.push(el("span", "k", `"${key}"`));
    nodes.push(document.createTextNode(": "));
    nodes.push(...jsonNodes(val, indent + 1));
    nodes.push(document.createTextNode(index < entries.length - 1 ? ",\n" : "\n"));
  });
  nodes.push(document.createTextNode(`${pad}}`));
  return nodes;
}

/* ---------- injection demo ---------- */

function renderInjection() {
  const { injection } = state.data;

  // Split on the <U+XXXX> markers the generator inserted, so hidden characters become visible chips.
  const parts = injection.raw_annotated.split(/(<U\+[0-9A-F]{4}>)/);
  $("#injection-raw").replaceChildren(
    ...parts.map((part) =>
      /^<U\+[0-9A-F]{4}>$/.test(part) ? el("span", "hidden-char", part.slice(1, -1)) : document.createTextNode(part)
    )
  );

  $("#injection-clean").textContent = injection.cleaned;
  $("#injection-removed").replaceChildren(...injection.removed.map((name) => el("code", null, name)));
}

/* ---------- test suite bars ---------- */

function renderSuites() {
  const { suites } = state.data.tests;
  const max = Math.max(...suites.map((s) => s.count));
  const rows = suites.map((suite) => {
    const row = el("div", "bar-row");
    row.append(el("span", "name", suite.key));
    const track = el("div", "bar-track");
    const fill = el("div", "bar-fill");
    track.appendChild(fill);
    row.append(track, el("span", "count", String(suite.count)), el("span", "what", suite.what));
    requestAnimationFrame(() => {
      fill.style.width = `${Math.max(6, (suite.count / max) * 100)}%`;
    });
    return row;
  });
  $("#suite-bars").replaceChildren(...rows);
}

